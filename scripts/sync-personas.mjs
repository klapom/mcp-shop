#!/usr/bin/env node
/**
 * sync-personas.mjs
 *
 * Reads all persona metadata.yaml files from agent-personas/personas/
 * and generates src/lib/personas.generated.ts + copies default webp assets.
 *
 * Run: node scripts/sync-personas.mjs
 * Called automatically via prebuild / predev hooks in package.json.
 */

import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'fs';
import { join, dirname, resolve } from 'path';
import { fileURLToPath } from 'url';
import { readdirSync } from 'fs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, '..');
const personasRoot = resolve(projectRoot, '../agent-personas/personas');
const publicPersonasDir = join(projectRoot, 'public', 'personas');
const outputFile = join(projectRoot, 'src', 'lib', 'personas.generated.ts');

// Minimal YAML parser — only handles simple key: value and nested blocks
// we need. We don't want a full yaml dep just for this script.
function parseSimpleYaml(content) {
  const result = {};
  const lines = content.split('\n');
  let i = 0;

  function parseLine(line) {
    const match = line.match(/^(\s*)([^:#\s][^:]*?):\s*(.*)$/);
    if (!match) return null;
    return {
      indent: match[1].length,
      key: match[2].trim(),
      value: match[3].trim(),
    };
  }

  function parseBlock(parentIndent) {
    const obj = {};
    while (i < lines.length) {
      const line = lines[i];
      if (!line.trim() || line.trim().startsWith('#')) { i++; continue; }
      const parsed = parseLine(line);
      if (!parsed) { i++; continue; }
      if (parsed.indent <= parentIndent) break;

      const nextLine = lines[i + 1];
      const nextParsed = nextLine ? parseLine(nextLine) : null;

      if (!parsed.value && nextParsed && nextParsed.indent > parsed.indent) {
        // nested block
        i++;
        obj[parsed.key] = parseBlock(parsed.indent);
      } else {
        // scalar value — strip quotes
        let val = parsed.value;
        if ((val.startsWith("'") && val.endsWith("'")) ||
            (val.startsWith('"') && val.endsWith('"'))) {
          val = val.slice(1, -1);
        }
        obj[parsed.key] = val;
        i++;
      }
    }
    return obj;
  }

  i = 0;
  return parseBlock(-1);
}

mkdirSync(publicPersonasDir, { recursive: true });

const personaDirs = readdirSync(personasRoot, { withFileTypes: true })
  .filter(d => d.isDirectory() && !d.name.startsWith('_'))
  .map(d => d.name);

const personas = [];

for (const key of personaDirs) {
  const metaPath = join(personasRoot, key, 'metadata.yaml');
  if (!existsSync(metaPath)) {
    console.warn(`[sync-personas] SKIP ${key}: no metadata.yaml`);
    continue;
  }

  const raw = readFileSync(metaPath, 'utf-8');
  const meta = parseSimpleYaml(raw);

  const displayName = meta.display_name || key;
  const descShort = meta.description_short || '';
  const wertstrom = meta.wertstrom || '';
  const customerFacing = meta.customer_facing === 'true';
  const imageDefault = meta.image?.default || `assets/${key}-default.webp`;

  // Copy webp asset
  const srcWebp = join(personasRoot, key, imageDefault);
  const destWebp = join(publicPersonasDir, `${key}-default.webp`);

  if (existsSync(srcWebp)) {
    copyFileSync(srcWebp, destWebp);
  } else {
    console.warn(`[sync-personas] WARNING: no webp for ${key} at ${srcWebp}`);
  }

  personas.push({
    key,
    displayName,
    descShort,
    wertstrom,
    customerFacing,
  });
}

console.log(`[sync-personas] Generated ${personas.length} personas`);

const ts = `// AUTO-GENERATED by scripts/sync-personas.mjs — DO NOT EDIT
// Re-run: node scripts/sync-personas.mjs

export interface Persona {
  key: string;
  displayName: string;
  descShort: string;
  wertstrom: string;
  customerFacing: boolean;
  avatarUrl: string;
}

export const PERSONAS: Persona[] = ${JSON.stringify(
  personas.map(p => ({
    ...p,
    avatarUrl: `/personas/${p.key}-default.webp`,
  })),
  null,
  2,
)};
`;

writeFileSync(outputFile, ts);
console.log(`[sync-personas] Wrote ${outputFile}`);
